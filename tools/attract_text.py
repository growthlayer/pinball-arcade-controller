#!/usr/bin/env python3
"""Text images for the marquee's colour attract show -> firmware/attract_text.h (8-bit alpha masks)."""
from PIL import Image, ImageDraw, ImageFont
from pathlib import Path
FB = "/System/Library/Fonts/Supplemental/"
BIG, MID, SMALL = (FB + "Arial Black.ttf", 21), (FB + "Arial Bold.ttf", 14), (FB + "Verdana Bold.ttf", 8)
SCROLL = ("   ***  WELCOME TO THE PINBALL ARCADE  ***  FREE PLAY  ***  HIGH SCORE  MRK  48,210,550  "
          "***  NUDGE GENTLY  ***  PRESS START TO PLAY  ***   ")
MASKS = [("M_PINBALL", "PINBALL", BIG), ("M_JACKPOT", "JACKPOT!", BIG), ("M_FREEPLAY", "FREE PLAY", MID),
         ("M_CONTROLLER", "CONTROLLER", SMALL), ("M_PRESSSTART", "PRESS START", SMALL), ("M_HIGHSCORE", "HIGH SCORE", SMALL),
         ("M_SCORE", "48,210,550", MID), ("M_MRK", "MRK", SMALL), ("M_SCROLL", SCROLL, MID)]
out = ["// Generated by tools/attract_text.py", "#pragma once", "#include <stdint.h>",
       "struct FxMask { uint16_t w, h; const uint8_t* a; };"]
for name, txt, (font, size) in MASKS:
    f = ImageFont.truetype(font, size); x0, y0, x1, y1 = f.getbbox(txt)
    im = Image.new("L", (x1 - x0 + 2, y1 - y0 + 2), 0); ImageDraw.Draw(im).text((1 - x0, 1 - y0), txt, font=f, fill=255)
    data = bytes(im.getdata())
    out.append(f"static const uint8_t {name}_a[{len(data)}] = {{" + ",".join(map(str, data)) + "};")
    out.append(f"static const FxMask {name} = {{{im.width}, {im.height}, {name}_a}};")
    print(name, im.size)
Path(__file__).resolve().parent.parent.joinpath("firmware", "attract_text.h").write_text("\n".join(out) + "\n")
