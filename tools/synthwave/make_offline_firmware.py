#!/usr/bin/env python3
"""Pre-render the OFFLINE show (offline.py) into firmware/attract_offline.h for the marquee's ESP32.

Storage: one 256-colour palette per scene (median cut over that scene's frames, transitions included), every
frame as 128x32 palette indices XOR'd with the previous frame and zlib-compressed. ZeDMD already links miniz,
so the ESP32 inflates one frame (4 KB) per 33 ms. The cycle is seamless: it ends with the transition back into
the first scene, and the player resets its previous-frame buffer to zeros when it wraps.

  python tools/synthwave/make_offline_firmware.py      -> firmware/attract_offline.h (+ size report)
"""
import sys, zlib
from pathlib import Path
import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import offline as O  # noqa: E402

OUT = HERE.parents[1] / "firmware" / "attract_offline.h"


def main():
    names, frames = [], []
    for name, f in O.show(loop=False):
        names.append(name); frames.append(f)
    n = len(frames)
    scene_of = [next(i for i, s in enumerate(O.SCENES) if s[0] == nm) for nm in names]
    palettes, pal_imgs = [], []
    for si in range(len(O.SCENES)):
        sample = np.concatenate([frames[i] for i in range(n) if scene_of[i] == si][::3], 0)
        q = Image.fromarray(sample).quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        pal = q.getpalette()[:768]
        pal += [0] * (768 - len(pal))
        palettes.append(pal); pal_imgs.append(q)
    blobs, prev, err = [], np.zeros((O.H, O.W), np.uint8), 0.0
    for i, f in enumerate(frames):
        idx = np.asarray(Image.fromarray(f).quantize(palette=pal_imgs[scene_of[i]], dither=Image.Dither.NONE))
        pal = np.array(palettes[scene_of[i]], np.float32).reshape(256, 3)
        err += float(np.abs(pal[idx] - f).mean())
        blobs.append(zlib.compress((idx ^ prev).tobytes(), 9))
        prev = idx
    offsets = np.cumsum([0] + [len(b) for b in blobs])
    data = b"".join(blobs)

    def arr(b, per=40):
        return ",\n".join("  " + ",".join(str(v) for v in b[k:k + per]) for k in range(0, len(b), per))

    with open(OUT, "w", newline="\n") as o:
        o.write("// GENERATED by tools/synthwave/make_offline_firmware.py from tools/synthwave/offline.py - do not edit.\n")
        o.write("// The marquee's OFFLINE show (NO SIGNAL / WAITING FOR PC / PC OFFLINE / NO INPUT), played by ZeDMD whenever\n")
        o.write("// the PC is silent. Same FxRender / FxRestart API as the old attract_fx.h.\n#pragma once\n#include <stdint.h>\n\n")
        o.write(f"#define OFFLINE_W {O.W}\n#define OFFLINE_H {O.H}\n#define OFFLINE_FRAMES {n}\n#define OFFLINE_SCENES {len(O.SCENES)}\n\n")
        o.write("static const uint8_t offline_palette[OFFLINE_SCENES][768] = {\n")
        o.write(",\n".join("{\n" + arr(p) + "\n}" for p in palettes) + "\n};\n")
        o.write("static const uint8_t offline_scene[OFFLINE_FRAMES] = {\n" + arr(scene_of) + "\n};\n")
        o.write("static const uint32_t offline_offset[OFFLINE_FRAMES + 1] = {\n" + arr([int(v) for v in offsets], 12) + "\n};\n")
        o.write(f"static const uint8_t offline_data[{len(data)}] = {{\n" + arr(data) + "\n};\n\n")
        o.write(PLAYER)
    print(f"{n} frames, {len(data) // 1024} KB compressed, mean colour error {err / n:.1f}/255 -> {OUT}")


PLAYER = r"""namespace offline {
static uint8_t idx[OFFLINE_W * OFFLINE_H];
static uint16_t frame = 0;
}

// fills rgb (W*H*3) with the next frame; call 30 times a second
static void FxRender(uint8_t* rgb) {
  using namespace offline;
  if (frame == 0) memset(idx, 0, sizeof(idx));                 // the stored deltas start from all zeros
  static uint8_t delta[OFFLINE_W * OFFLINE_H];                  // static: off the loop task's stack
  mz_ulong len = sizeof(delta);
  const uint32_t a = offline_offset[frame], b = offline_offset[frame + 1];
  if (mz_uncompress(delta, &len, offline_data + a, b - a) == MZ_OK && len == sizeof(delta))
    for (uint16_t i = 0; i < sizeof(idx); i++) idx[i] ^= delta[i];
  const uint8_t* pal = offline_palette[offline_scene[frame]];
  for (uint16_t i = 0; i < sizeof(idx); i++) {
    const uint8_t* c = pal + idx[i] * 3;
    rgb[i * 3] = c[0]; rgb[i * 3 + 1] = c[1]; rgb[i * 3 + 2] = c[2];
  }
  if (++frame >= OFFLINE_FRAMES) frame = 0;
}

static void FxRestart() { offline::frame = 0; }
"""

if __name__ == "__main__":
    main()
